/* The range in oled_text_xy is 0x20...0x5A, that is exactly 59 glyphs.
Without this check a truncated table would silently read somebody else's rodata. */
_Static_assert(sizeof FONT / sizeof FONT[0] == 59, "FONT: 0x20...0x5A required");

static i2c_master_dev_handle_t s_dev;
static uint8_t s_fb[128 * 8];
static int s_ok;

static esp_err_t tx(const uint8_t* d, size_t n) {
  return i2c_master_transmit(s_dev, d, n, I2C_TIMEOUT_MS);
}

esp_err_t oled_init(i2c_master_dev_handle_t dev) {
  /* The leading byte 0x00 is the control byte (Co=0, D/C#=0), not RTC register 0x00. */
  static const uint8_t cmd[] = {
      0x00,        // control byte: commands only from here on
      0xAE,        // display off
      0xD5, 0x80,  // clock divide
      0xA8, 0x3F,  // multiplex ratio: 64 rows
      0xD3, 0x00,  // display offset 0
      0x40,        // start line 0
      0x8D, 0x14,  // charge pump on
      0x20, 0x02,  // memory mode: page addressing — for set_pos()
      0xA1,        // segment remap
      0xC8,        // COM scan reverse
      0xDA, 0x12,  // COM pins: alternative
      0x81, 0x7F,  // contrast
      0xA4,        // output from RAM, not all-on
      0xA6,        // normal, not inverted
      0xAF,        // display on
  };

  s_dev = dev;
  s_ok = 0;
  memset(s_fb, 0, sizeof(s_fb));
  if (tx(cmd, sizeof(cmd)) != ESP_OK) {
    return ESP_FAIL;
  }

  s_ok = 1;
  return ESP_OK;
}

/* Cursor in page mode: page 0...7, then the low and high nibble of the column. */
static void set_pos(uint8_t page, uint8_t col) {
  uint8_t cmd[] = {
      0x00,
      (uint8_t)(0xB0 | (page & 7)),
      (uint8_t)(0x00 | (col & 0x0F)),
      (uint8_t)(0x10 | (col >> 4)),
  };
  tx(cmd, sizeof(cmd));
}

void oled_fb_clear(void) {
  memset(s_fb, 0, sizeof(s_fb));
}

void oled_pixel(int x, int y, int on) {
  uint8_t* p;
  uint8_t m;
  if ((unsigned)x >= 128u || (unsigned)y >= 64u) {
    return;
  }
  p = &s_fb[(y >> 3) * 128 + x];
  m = (uint8_t)(1u << (y & 7));
  if (on) {
    *p |= m;
  } else {
    *p = (uint8_t)(*p & (uint8_t)~m);
  }
}

void oled_fill(int x, int y, int w, int h, int on) {
  int i, j;
  for (j = 0; j < h; j++) {
    for (i = 0; i < w; i++) {
      oled_pixel(x + i, y + j, on);
    }
  }
}

void oled_text_xy(int x, int y, const char* s) {
  for (; *s; s++, x += 6) {
    unsigned idx = (unsigned)(uint8_t)*s;
    const uint8_t* g = FONT[0];
    int col, row;
    if (idx >= 'a' && idx <= 'z') {
      idx -= 32;
    }

    if (idx >= 32 && idx <= 90) {
      g = FONT[idx - 32];
    }

    for (col = 0; col < 5; col++) {
      for (row = 0; row < 8; row++) {
        oled_pixel(x + col, y + row, (g[col] >> row) & 1);
      }
    }
  }
}

void oled_flush(void) {
  uint8_t buf[129];
  int page;
  if (!s_ok) {
    return;
  }

  /* The leading byte 0x40 is the control byte for data (Co=0, D/C#=1). */
  buf[0] = 0x40;
  for (page = 0; page < 8; page++) {
    set_pos((uint8_t)page, 0);
    memcpy(buf + 1, s_fb + page * 128, 128);
    tx(buf, sizeof(buf));
  }
}
